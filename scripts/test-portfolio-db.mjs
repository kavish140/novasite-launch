import { PGlite } from "@electric-sql/pglite";
import {readFile} from "node:fs/promises";
import assert from "node:assert/strict";
const db=new PGlite();
await db.exec(`
create role anon; create role authenticated;
create schema auth;
create function public.is_site_admin() returns boolean language sql as $$ select current_setting('test.admin',true)='yes' $$;
revoke all on function public.is_site_admin() from public;
grant execute on function public.is_site_admin() to authenticated;
`);
await db.exec(await readFile("supabase/migrations/20261118100613_portfolio_projects.sql","utf8"));
assert.equal((await db.query("select count(*)::int n from portfolio_projects where project->>'liveUrl' like '%aismartkit.tech%'")).rows[0].n,0);
await db.exec("set role anon");
assert.ok((await db.query("select * from portfolio_projects")).rows.length>0);
await assert.rejects(db.exec("delete from portfolio_projects"));
await assert.rejects(db.exec("update portfolio_projects set position=99"));
await db.exec("set role authenticated; set test.admin='no'");
assert.equal((await db.query("delete from portfolio_projects returning slug")).rows.length,0);
await db.exec("set test.admin='yes'");
const row=(await db.query("select * from portfolio_projects limit 1")).rows[0];
await db.query("insert into portfolio_projects(slug,project,category) values($1,$2,'client')",["new-project",{...row.project,slug:"new-project",title:"New project"}]);
assert.equal((await db.query("update portfolio_projects set is_visible=false,revision=2 where slug='new-project' and revision=1 returning slug")).rows.length,1);
assert.equal((await db.query("update portfolio_projects set position=99 where slug='new-project' and revision=1 returning slug")).rows.length,0);
await assert.rejects(db.query("update portfolio_projects set project=$1 where slug='new-project'",[{...row.project,slug:"new-project",liveUrl:"javascript:alert(1)"}]));
await db.exec("set role anon");
assert.equal((await db.query("select * from portfolio_projects where slug='new-project'")).rows.length,0);
await db.exec("set role authenticated; set test.admin='yes'");
assert.equal((await db.query("delete from portfolio_projects where slug='new-project' returning slug")).rows.length,1);
console.log("Portfolio database: seed removal, public read, admin CRUD, non-admin denial, hidden rows, stale revision and URL constraints passed.");
await db.close();
